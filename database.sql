CREATE VIEW public.v_pet_list
WITH (security_invoker = true) AS
SELECT p.pet_id,p.pet_code,p.pet_name,c.customer_code,c.full_name AS owner_name,
       p.species,p.breed,p.age_years,p.age_months,p.gender,p.health_status,
       p.vaccination_record,p.medical_notes
FROM public.pets p
JOIN public.customers c ON c.customer_id=p.customer_id;

CREATE VIEW public.v_current_confinement
WITH (security_invoker = true) AS
SELECT co.confinement_id,p.pet_code,p.pet_name,c.full_name AS owner_name,
       co.admission_date,co.expected_discharge_date,co.kennel_cage,
       co.status,co.reason,co.veterinary_notes
FROM public.confinements co
JOIN public.pets p ON p.pet_id=co.pet_id
JOIN public.customers c ON c.customer_id=co.customer_id
WHERE co.status <> 'Discharged';

CREATE VIEW public.v_product_inventory
WITH (security_invoker = true) AS
SELECT p.product_id,p.sku,p.product_name,cat.category_name,s.supplier_name,
       COALESCE(i.quantity,0) AS quantity,p.reorder_level,p.selling_price,
       CASE
         WHEN COALESCE(i.quantity,0)=0 THEN 'Out of Stock'
         WHEN COALESCE(i.quantity,0)<=p.reorder_level THEN 'Low Stock'
         ELSE 'In Stock'
       END AS stock_status
FROM public.products p
JOIN public.categories cat ON cat.category_id=p.category_id
LEFT JOIN public.suppliers s ON s.supplier_id=p.supplier_id
LEFT JOIN public.inventory i ON i.product_id=p.product_id;

CREATE VIEW public.v_sales_summary
WITH (security_invoker = true) AS
SELECT s.sale_id,s.invoice_number,s.sale_date,
       COALESCE(c.full_name,'Walk-in Customer') AS customer_name,
       COALESCE(u.full_name,'') AS cashier,
       s.service_type,s.service_description,s.subtotal,s.discount,
       s.total_amount,s.payment_method,s.reference_number,
       s.amount_paid,s.change_amount,s.status
FROM public.sales s
LEFT JOIN public.customers c ON c.customer_id=s.customer_id
LEFT JOIN public.users u ON u.user_id=s.sold_by;

