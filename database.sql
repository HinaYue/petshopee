CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TABLE public.users (
  user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(50) NOT NULL UNIQUE,
  password varchar(255) NOT NULL,
  full_name varchar(100) NOT NULL,
  role varchar(20) NOT NULL DEFAULT 'Staff'
    CHECK (role IN ('Administrator','Staff')),
  status varchar(20) NOT NULL DEFAULT 'Active'
    CHECK (status IN ('Active','Inactive')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.user_permissions (
  permission_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(user_id)
    ON UPDATE CASCADE ON DELETE CASCADE,
  permission_key varchar(80) NOT NULL,
  allowed boolean NOT NULL DEFAULT false,
  UNIQUE (user_id, permission_key)
);

CREATE TABLE public.customers (
  customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_code varchar(20) NOT NULL UNIQUE,
  full_name varchar(120) NOT NULL,
  phone varchar(30),
  email varchar(120),
  address varchar(255),
  status varchar(20) NOT NULL DEFAULT 'Active'
    CHECK (status IN ('Active','Inactive')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.pets (
  pet_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_code varchar(20) NOT NULL UNIQUE,
  customer_id bigint NOT NULL REFERENCES public.customers(customer_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  pet_name varchar(100) NOT NULL,
  species varchar(50),
  breed varchar(100),
  age_years smallint NOT NULL DEFAULT 0 CHECK (age_years >= 0),
  age_months smallint NOT NULL DEFAULT 0 CHECK (age_months >= 0),
  gender varchar(20) NOT NULL DEFAULT 'Unknown'
    CHECK (gender IN ('Male','Female','Unknown')),
  health_status varchar(30) NOT NULL DEFAULT 'Healthy'
    CHECK (health_status IN ('Healthy','Under Observation','Needs Treatment','Recovering','Critical')),
  vaccination_record text,
  medical_notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.confinements (
  confinement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id bigint NOT NULL REFERENCES public.pets(pet_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  customer_id bigint NOT NULL REFERENCES public.customers(customer_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  admission_date timestamptz NOT NULL,
  expected_discharge_date timestamptz,
  actual_discharge_date timestamptz,
  kennel_cage varchar(50),
  status varchar(30) NOT NULL DEFAULT 'Admitted'
    CHECK (status IN ('Admitted','Under Observation','Stable','Recovering','Critical','Ready for Discharge','Discharged')),
  reason text NOT NULL,
  veterinary_notes text,
  created_by bigint REFERENCES public.users(user_id)
    ON UPDATE CASCADE ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.categories (
  category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_name varchar(100) NOT NULL UNIQUE,
  description varchar(255),
  status varchar(20) NOT NULL DEFAULT 'Active'
    CHECK (status IN ('Active','Inactive')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.suppliers (
  supplier_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_code varchar(20) NOT NULL UNIQUE,
  supplier_name varchar(120) NOT NULL,
  contact_person varchar(100),
  phone varchar(30),
  email varchar(120),
  address varchar(255),
  status varchar(20) NOT NULL DEFAULT 'Active'
    CHECK (status IN ('Active','Inactive')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.products (
  product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku varchar(50) NOT NULL UNIQUE,
  category_id bigint NOT NULL REFERENCES public.categories(category_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  supplier_id bigint REFERENCES public.suppliers(supplier_id)
    ON UPDATE CASCADE ON DELETE SET NULL,
  product_name varchar(150) NOT NULL,
  description text,
  unit varchar(30) NOT NULL DEFAULT 'piece',
  cost_price numeric(12,2) NOT NULL DEFAULT 0.00 CHECK (cost_price >= 0),
  selling_price numeric(12,2) NOT NULL DEFAULT 0.00 CHECK (selling_price >= 0),
  reorder_level integer NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
  status varchar(20) NOT NULL DEFAULT 'Active'
    CHECK (status IN ('Active','Inactive')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.inventory (
  inventory_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL UNIQUE REFERENCES public.products(product_id)
    ON UPDATE CASCADE ON DELETE CASCADE,
  quantity integer NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.inventory_movements (
  movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES public.products(product_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  movement_type varchar(10) NOT NULL
    CHECK (movement_type IN ('IN','OUT','SET')),
  quantity integer NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  previous_quantity integer NOT NULL DEFAULT 0 CHECK (previous_quantity >= 0),
  new_quantity integer NOT NULL DEFAULT 0 CHECK (new_quantity >= 0),
  notes varchar(255),
  created_by bigint REFERENCES public.users(user_id)
    ON UPDATE CASCADE ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.sales (
  sale_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number varchar(40) NOT NULL UNIQUE,
  customer_id bigint REFERENCES public.customers(customer_id)
    ON UPDATE CASCADE ON DELETE SET NULL,
  sold_by bigint REFERENCES public.users(user_id)
    ON UPDATE CASCADE ON DELETE SET NULL,
  service_type varchar(80) NOT NULL DEFAULT 'Product Sale',
  service_description varchar(255),
  sale_date timestamptz NOT NULL DEFAULT now(),
  subtotal numeric(12,2) NOT NULL DEFAULT 0.00 CHECK (subtotal >= 0),
  discount numeric(12,2) NOT NULL DEFAULT 0.00 CHECK (discount >= 0),
  total_amount numeric(12,2) NOT NULL DEFAULT 0.00 CHECK (total_amount >= 0),
  payment_method varchar(30) NOT NULL DEFAULT 'Cash'
    CHECK (payment_method IN ('Cash','Card','GCash','Bank Transfer','Other')),
  reference_number varchar(100),
  amount_paid numeric(12,2) NOT NULL DEFAULT 0.00 CHECK (amount_paid >= 0),
  change_amount numeric(12,2) NOT NULL DEFAULT 0.00 CHECK (change_amount >= 0),
  status varchar(20) NOT NULL DEFAULT 'Completed'
    CHECK (status IN ('Completed','Voided','Pending')),
  notes varchar(255)
);

CREATE TABLE public.sale_items (
  sale_item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id bigint NOT NULL REFERENCES public.sales(sale_id)
    ON UPDATE CASCADE ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES public.products(product_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  quantity integer NOT NULL CHECK (quantity > 0),
  unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
  discount numeric(12,2) NOT NULL DEFAULT 0.00 CHECK (discount >= 0),
  line_total numeric(12,2) NOT NULL CHECK (line_total >= 0)
);

CREATE TABLE public.settings (
  setting_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
